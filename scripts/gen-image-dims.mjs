/* Regenerates src/lib/image-dims.js from the files in src/images/.
   Run after adding or replacing artwork:  npm run images:dims

   The dimensions are what let an <img> reserve its box before loading.
   Without them a height:auto image is 0px tall, and a 0px-tall element
   never intersects the viewport — so loading="lazy" never fires and the
   image never appears. */
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
const run = promisify(execFile);

const DIR = new URL("../src/images/", import.meta.url);
const files = (await readdir(DIR)).filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f));

const dims = {};
for (const f of files.sort()) {
  const { stdout } = await run("sips", ["-g", "pixelWidth", "-g", "pixelHeight",
    fileURLToPath(new URL(f, DIR))]);
  const w = +(stdout.match(/pixelWidth:\s*(\d+)/)?.[1] ?? 0);
  const h = +(stdout.match(/pixelHeight:\s*(\d+)/)?.[1] ?? 0);
  if (w && h) dims[f.replace(/\.\w+$/, "")] = [w, h];
}

const body = Object.entries(dims).map(([k, v]) => `  "${k}": [${v[0]}, ${v[1]}]`).join(",\n");
await writeFile(new URL("../src/lib/image-dims.js", import.meta.url),
`/* Generated by scripts/gen-image-dims.mjs — do not edit by hand.
   Intrinsic pixel dimensions, used to reserve each image's box before it
   loads. Regenerate with: npm run images:dims */
export const IMAGE_DIMS = {
${body}
};

/** width / height, or null if the file isn't in the map */
export function imageRatio(name) {
  const d = IMAGE_DIMS[name];
  return d ? d[0] / d[1] : null;
}
`);
console.log(`wrote ${Object.keys(dims).length} entries`);
